def env_bool(nome, padrao=False):
    valor = os.environ.get(nome)
    if valor is None:
        return padrao
    return valor.strip().lower() in ('1', 'true', 'yes', 'on')


def env_lista(nome, padrao=()):
    valor = os.environ.get(nome)
    if valor is None:
        return list(padrao)
    return [item.strip() for item in valor.split(',') if item.strip()]


